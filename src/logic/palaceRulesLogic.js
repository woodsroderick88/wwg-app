function getHexagramNumber(hexagram) {
  return Number(hexagram?.kingWen?.number || 0);
}

function getShiYingInfo(hexagram) {
  const hexagramNumber = getHexagramNumber(hexagram);
  const tableEntry = SHI_YING_BY_HEXAGRAM_NUMBER[hexagramNumber];

  if (tableEntry) {
    return {
      ...tableEntry,
      hexagramNumber,
    };
  }

  return {
    hexagramNumber,
    palace: hexagram?.palace?.palace || "Unknown Palace",
    stage: "Unknown palace stage",
    shiLine: 3,
    yingLine: 6,
    fallback: true,
  };
}

function getLineByNumber(sixKinRows, lineNumber) {
  return sixKinRows.find((row) => row.lineNumber === lineNumber) || null;
}

function formatLine(row) {
  if (!row) {
    return "Not available";
  }

  const movingText = row.moving ? "moving" : "static";
  const conditionText = row.condition?.summary || "Unknown condition";

  return `Line ${row.lineNumber}: ${row.branch?.label || "Unknown branch"} / ${
    row.sixKin || "Unknown six-kin"
  } / ${conditionText} / ${movingText}`;
}

function getFocusRelationshipToShiYing(focusRows, shiLine, yingLine) {
  if (!Array.isArray(focusRows) || focusRows.length === 0) {
    return {
      label: "Focus not visible",
      text:
        "The selected focus does not appear directly in the visible six lines. Hidden/Flying Spirit logic may be needed later.",
    };
  }

  const focusLineNumbers = focusRows.map((row) => row.lineNumber);
  const touchesShi = focusLineNumbers.includes(shiLine);
  const touchesYing = focusLineNumbers.includes(yingLine);

  if (touchesShi && touchesYing) {
    return {
      label: "Focus touches Shi and Ying",
      text:
        "The selected focus appears on both the Shi/Self side and the Ying/Other side. This makes the matter central to both parties or both sides of the situation.",
    };
  }

  if (touchesShi) {
    return {
      label: "Focus touches Shi",
      text:
        "The selected focus appears on the Shi/Self line. This ties the matter directly to the querent, the self-position, or the side asking the question.",
    };
  }

  if (touchesYing) {
    return {
      label: "Focus touches Ying",
      text:
        "The selected focus appears on the Ying/Other line. This ties the matter directly to the other party, outside condition, opposing side, or object side of the question.",
    };
  }

  return {
    label: "Focus separate from Shi/Ying",
    text:
      "The selected focus is visible, but it does not sit directly on the Shi or Ying line. The matter is present, but its relationship to Self/Other needs further rule comparison.",
  };
}

function getMovingRelationshipToShiYing(movingLines, shiLine, yingLine) {
  const movingLineNumbers = Array.isArray(movingLines) ? movingLines : [];
  const shiMoves = movingLineNumbers.includes(shiLine);
  const yingMoves = movingLineNumbers.includes(yingLine);

  if (shiMoves && yingMoves) {
    return "Both Shi and Ying are moving. This shows active change on both the self side and the other/object side.";
  }

  if (shiMoves) {
    return "Shi is moving. This shows the querent/self side is active, changing, or under pressure.";
  }

  if (yingMoves) {
    return "Ying is moving. This shows the other/object side is active, changing, or under pressure.";
  }

  if (movingLineNumbers.length > 0) {
    return `Moving lines are present on line ${movingLineNumbers.join(
      ", "
    )}, but not directly on Shi or Ying. Future palace rules should compare how those moving lines affect Shi/Ying.`;
  }

  return "No moving lines are present. Shi/Ying are static at this MVP layer unless hidden/flying spirit logic changes the reading.";
}

export function buildPalaceRulesPreview({
  originalHexagram,
  transformedHexagram,
  sixKinRows,
  selectedFocus,
  focusRows,
  movingLines,
}) {
  const originalShiYing = getShiYingInfo(originalHexagram);
  const transformedShiYing = getShiYingInfo(transformedHexagram);

  const shiLine = originalShiYing.shiLine;
  const yingLine = originalShiYing.yingLine;

  const shiRow = getLineByNumber(sixKinRows, shiLine);
  const yingRow = getLineByNumber(sixKinRows, yingLine);

  const focusRelationship = getFocusRelationshipToShiYing(
    focusRows,
    shiLine,
    yingLine
  );

  const movingRelationship = getMovingRelationshipToShiYing(
    movingLines,
    shiLine,
    yingLine
  );

  const focusLineText =
    focusRows?.length > 0
      ? focusRows.map((row) => `line ${row.lineNumber}`).join(", ")
      : "no visible line";

  const notes = [
    {
      title: "Original palace",
      text: `The original hexagram belongs to ${
        originalHexagram?.palace?.palace || "Unknown Palace"
      }, with ${
        originalHexagram?.palace?.element || "Unknown"
      } as the working palace element.`,
    },
    {
      title: "Original Shi/Ying assignment",
      text: originalShiYing.fallback
        ? `No exact Shi/Ying table entry was found for this hexagram, so the app is using a fallback Shi line ${shiLine} and Ying line ${yingLine}.`
        : `The original hexagram is a ${originalShiYing.stage} in ${originalShiYing.palace}. Shi is line ${shiLine}; Ying is line ${yingLine}.`,
    },
    {
      title: "Shi / Self line",
      text: `Shi is line ${shiLine}. ${formatLine(
        shiRow
      )}. This line represents the self side, querent position, or the side asking the question.`,
    },
    {
      title: "Ying / Other line",
      text: `Ying is line ${yingLine}. ${formatLine(
        yingRow
      )}. This line represents the other party, object side, outside condition, or opposing side.`,
    },
    {
      title: "Transformed palace reference",
      text: `The transformed hexagram belongs to ${
        transformedHexagram?.palace?.palace || "Unknown Palace"
      }, with ${
        transformedHexagram?.palace?.element || "Unknown"
      } as the transformed palace element. Its table stage is ${
        transformedShiYing.stage
      }, with transformed Shi line ${transformedShiYing.shiLine} and Ying line ${
        transformedShiYing.yingLine
      }. Future rules can compare original Shi/Ying against transformed Shi/Ying.`,
    },
    {
      title: focusRelationship.label,
      text: `${selectedFocus} appears on ${focusLineText}. ${focusRelationship.text}`,
    },
    {
      title: "Moving-line relationship to Shi/Ying",
      text: movingRelationship,
    },
    {
      title: "Hidden / Flying spirit placeholder",
      text:
        "Hidden Spirit / 伏神 and Flying Spirit / 飞神 logic is now entering foundation mode. Future upgrades should compare concealed useful spirits against Shi, Ying, moving lines, and covering lines with a complete traditional table.",
    },
  ];

  const summary = `Original palace: ${
    originalHexagram?.palace?.palace || "Unknown Palace"
  }. Transformed palace: ${
    transformedHexagram?.palace?.palace || "Unknown Palace"
  }. Shi line: ${shiLine}. Ying line: ${yingLine}. ${
    focusRelationship.text
  } ${movingRelationship}`;

  return {
    originalHexagramNumber: originalShiYing.hexagramNumber,
    transformedHexagramNumber: transformedShiYing.hexagramNumber,

    originalPalace: originalHexagram?.palace?.palace || "Unknown Palace",
    originalElement: originalHexagram?.palace?.element || "Unknown",
    transformedPalace: transformedHexagram?.palace?.palace || "Unknown Palace",
    transformedElement: transformedHexagram?.palace?.element || "Unknown",

    shiLine,
    yingLine,
    shiRow,
    yingRow,

    originalShiYing,
    transformedShiYing,

    notes,
    summary,
  };
}